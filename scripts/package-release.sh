#!/usr/bin/env bash
# scripts/package-release.sh — assemble one downloadable `ling` archive.
#
#   scripts/package-release.sh <target-triple>
#
# Reads the binary from $PROFILE_DIR (default target/release) and writes
# dist/ling-<version>-<target>/ together with its .tar.gz and .sha256.
#
# The version is taken from the binary itself rather than from a manifest, so an
# archive can never be named for a version the binary does not report. The
# workflow that calls this additionally pins it to the git tag.
#
# No dictionary ships in the archive. The bytes here are code under the
# repository's MIT license plus generated third-party notices; a dictionary is
# licensed data with its own acquisition path (README, DICTIONARIES.md).

set -euo pipefail

target=${1:?usage: scripts/package-release.sh <target-triple>}
repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
profile_dir=${PROFILE_DIR:-$repo_root/target/release}
dist_dir=${DIST_DIR:-$repo_root/dist}

binary="$profile_dir/ling"
if [ ! -x "$binary" ]; then
    echo "error: no executable at $binary (set PROFILE_DIR)" >&2
    exit 1
fi

version=$("$binary" --version | awk '{print $2}')
if [ -z "$version" ]; then
    echo "error: $binary reports no version" >&2
    exit 1
fi

name="ling-$version-$target"
out="$dist_dir/$name"
rm -rf "$out"
mkdir -p \
    "$out/bin" \
    "$out/share/bash-completion/completions" \
    "$out/share/zsh/site-functions" \
    "$out/share/fish/vendor_completions.d" \
    "$out/share/man/man1"

install -m 755 "$binary" "$out/bin/ling"

# Completions and manual pages are generated by the released binary itself, so
# they cannot describe a different build than the one in bin/.
"$out/bin/ling" completions bash > "$out/share/bash-completion/completions/ling"
"$out/bin/ling" completions zsh > "$out/share/zsh/site-functions/_ling"
"$out/bin/ling" completions fish > "$out/share/fish/vendor_completions.d/ling.fish"

# `ling manpages` creates the directory it writes into and refuses an existing
# one, so it is handed a path that does not exist yet.
man_stage="$out/man-pages"
"$out/bin/ling" manpages --output "$man_stage" > /dev/null
cp "$man_stage"/*.1 "$out/share/man/man1/"
rm -rf "$man_stage"

cp "$repo_root/LICENSE" "$out/LICENSE"
python3 "$repo_root/scripts/third-party-notices.py" --target "$target" \
    > "$out/THIRD-PARTY-NOTICES.md"

# Everything the packaging step wrote must be non-empty: an empty completion or
# a man page set that silently wrote nothing fails here rather than in a user's
# shell.
for required in \
    "$out/bin/ling" \
    "$out/share/bash-completion/completions/ling" \
    "$out/share/zsh/site-functions/_ling" \
    "$out/share/fish/vendor_completions.d/ling.fish" \
    "$out/share/man/man1/ling.1" \
    "$out/share/man/man1/ling-matches.1" \
    "$out/share/man/man1/ling-corpus-build.1" \
    "$out/LICENSE" \
    "$out/THIRD-PARTY-NOTICES.md"; do
    if [ ! -s "$required" ]; then
        echo "error: $required is missing or empty" >&2
        exit 1
    fi
done

tar -C "$dist_dir" -czf "$dist_dir/$name.tar.gz" "$name"

# macOS runners ship shasum but not sha256sum.
if command -v sha256sum > /dev/null; then
    (cd "$dist_dir" && sha256sum "$name.tar.gz" > "$name.tar.gz.sha256")
else
    (cd "$dist_dir" && shasum -a 256 "$name.tar.gz" > "$name.tar.gz.sha256")
fi

echo "$dist_dir/$name.tar.gz"
