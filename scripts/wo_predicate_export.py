#!/usr/bin/env python3
"""Export a Soranoha kernel run as ling JSONL and as sentence lines for GiNZA.

The comparison in ``scripts/wo_predicate_compare.py`` runs one
morpheme-adjacency catalog over a Vibrato/UniDic analysis and one dependency
catalog over a GiNZA parse of the *same sentences*. Both analyses
must therefore start from one sentence inventory whose identity (document,
sentence ordinal) is fixed before either analyzer sees it. This script owns
that inventory.

Inputs are a Soranoha kernel state root (``--kernel-root``) and the run record
whose ``works`` map names each work's plaintext blob. Every blob is read from
the kernel's content-addressed store (``kura/objects/<hex[0:2]>/<hex>``);
nothing is rebuilt. Bibliographic metadata comes from the Aozora Bunko
``list_person_all_extended_utf8.csv`` the same run recorded under
``catalog_csv_hash``, so the export cannot drift from the run it names.

Two outputs, written under ``--out-dir``:

* ``aozora.jsonl`` — native ling JSONL, one work per line:
  ``{"title", "slug", "work_id", "authors", "translators", "translated",
  "ndc", "orthography", "sentences": [...]}``. This root is what
  ``ling corpus build`` prepares with the Vibrato analyzer.
* ``aozora-sentences.txt`` — the same sentences, one per line, in the same
  order, preceded by ``# newdoc id = <slug>`` and ``# sent_id = <slug>:<n>``
  comments that ``ginza -c print`` passes through to its CoNLL-U output. With
  ``ginza -d`` (sentencizer disabled) each line is exactly one sentence, so the
  CoNLL-U sentence ordinal within a document equals the JSONL index.
* ``export-manifest.json`` — counts, the run record path, the catalog CSV hash,
  the sentence-splitting rule, and this file's own SHA-256 digest.

Sentence splitting is deliberately simple and stated once, here: each
plaintext line is a paragraph; tabs become single spaces in both outputs; leading and trailing whitespace (including the
U+3000 paragraph indent) is removed; a sentence ends after a run of ``。！？``
together with any closing quotation or bracket characters that immediately
follow it; a paragraph remainder without a terminator is one sentence. Empty
sentences are dropped. The rule is recorded in the manifest so the inventory
can be regenerated byte-identically.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

SENTENCE_RULE = (
    "paragraph = plaintext line; tabs to spaces; strip; split after [。！？]+ plus any following "
    "closing marks [」』）〕】〉》]; keep remainder; drop empty"
)
_SENTENCE = re.compile(r"[^。！？]*[。！？]+[」』）〕】〉》]*|[^。！？]+$")


def split_sentences(paragraph: str) -> list[str]:
    text = paragraph.replace("\t", " ").strip()
    if not text:
        return []
    return [s for s in (m.group(0).strip() for m in _SENTENCE.finditer(text)) if s]


def blob_path(cas_dir: Path, hex_digest: str) -> Path:
    if len(hex_digest) != 64:
        raise ValueError(f"not a sha256 hex digest: {hex_digest!r}")
    return cas_dir / hex_digest[:2] / hex_digest


def load_catalog(csv_bytes: bytes) -> dict[int, dict]:
    """Map Aozora work id to title, contributors by role, NDC, and orthography."""
    rows = csv.DictReader(csv_bytes.decode("utf-8-sig").splitlines())
    works: dict[int, dict] = {}
    for row in rows:
        work_id = int(row["作品ID"])
        entry = works.setdefault(
            work_id,
            {
                "title": row["作品名"],
                "ndc": row["分類番号"],
                "orthography": row["文字遣い種別"],
                "first_published": row["初出"],
                "contributors": defaultdict(list),
            },
        )
        name = "".join(part for part in (row["姓"], row["名"]) if part)
        entry["contributors"][row["役割フラグ"]].append(name)
    return works


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--kernel-root", type=Path, required=True)
    parser.add_argument("--run", type=Path, required=True, help="kernel run JSON")
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--limit", type=int, default=None, help="first N works (sorted by slug)")
    args = parser.parse_args(argv)

    run = json.loads(args.run.read_text(encoding="utf-8"))
    cas_dir = args.kernel_root / "kura" / "objects"
    catalog = load_catalog(blob_path(cas_dir, run["catalog_csv_hash"]).read_bytes())

    args.out_dir.mkdir(parents=True, exist_ok=True)
    jsonl_path = args.out_dir / "aozora.jsonl"
    lines_path = args.out_dir / "aozora-sentences.txt"

    slugs = sorted(run["works"])
    if args.limit is not None:
        slugs = slugs[: args.limit]

    works_written = 0
    sentences_written = 0
    missing_plaintext = 0
    missing_catalog = 0
    with jsonl_path.open("w", encoding="utf-8") as jsonl, lines_path.open(
        "w", encoding="utf-8"
    ) as lines:
        for slug in slugs:
            work = run["works"][slug]
            digest = work.get("plaintext")
            if not digest:
                missing_plaintext += 1
                continue
            text = blob_path(cas_dir, digest).read_text(encoding="utf-8")
            sentences = [s for para in text.split("\n") for s in split_sentences(para)]
            if not sentences:
                continue
            work_id = int(slug.split("_", 1)[0])
            meta = catalog.get(work_id)
            if meta is None:
                missing_catalog += 1
                meta = {
                    "title": "",
                    "ndc": "",
                    "orthography": "",
                    "first_published": "",
                    "contributors": {},
                }
            contributors = meta["contributors"]
            authors = contributors.get("著者", [])
            translators = contributors.get("翻訳者", [])
            record = {
                "title": meta["title"],
                "slug": slug,
                "work_id": work_id,
                "authors": authors,
                "translators": translators,
                "translated": bool(translators),
                "ndc": meta["ndc"],
                "orthography": meta["orthography"],
                "sentences": sentences,
            }
            jsonl.write(json.dumps(record, ensure_ascii=False) + "\n")
            lines.write(f"# newdoc id = {slug}\n")
            for index, sentence in enumerate(sentences):
                lines.write(f"# sent_id = {slug}:{index}\n")
                lines.write(sentence + "\n")
            works_written += 1
            sentences_written += len(sentences)

    manifest = {
        "run": str(args.run),
        "kernel_root": str(args.kernel_root),
        "aozora_git_commit": run.get("aozora_git_commit"),
        "catalog_csv_hash": run["catalog_csv_hash"],
        "sentence_rule": SENTENCE_RULE,
        "works": works_written,
        "sentences": sentences_written,
        "works_without_plaintext": missing_plaintext,
        "works_without_catalog_entry": missing_catalog,
        "limit": args.limit,
        "jsonl_sha256": hashlib.sha256(jsonl_path.read_bytes()).hexdigest(),
        "sentences_sha256": hashlib.sha256(lines_path.read_bytes()).hexdigest(),
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    (args.out_dir / "export-manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(manifest, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
