use std::sync::LazyLock;

use lingrep_core::token_match::{TokenAttributeIndex, TokenAttributeIndex::*};

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum TokenFieldGroupKey {
    Surface,
    Lexeme,
    Pos,
    Forms,
    Reading,
    Variation,
    Accent,
}

impl TokenFieldGroupKey {
    pub const fn label_en(self) -> &'static str {
        match self {
            Self::Surface => "Surface",
            Self::Lexeme => "Lexeme",
            Self::Pos => "Part of speech",
            Self::Forms => "Forms",
            Self::Reading => "Reading",
            Self::Variation => "Variation",
            Self::Accent => "Accent",
        }
    }

    pub const fn label_ja(self) -> &'static str {
        match self {
            Self::Surface => "表層",
            Self::Lexeme => "語彙素・見出し",
            Self::Pos => "品詞",
            Self::Forms => "活用形",
            Self::Reading => "読み",
            Self::Variation => "語形変異",
            Self::Accent => "アクセント",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TokenFieldMeta {
    pub attribute: TokenAttributeIndex,
    pub key: &'static str,
    pub label_ja: &'static str,
    pub label_en: &'static str,
    pub group: TokenFieldGroupKey,
    pub order: u8,
    pub summary: bool,
    pub help: &'static str,
}

const fn meta(
    attribute: TokenAttributeIndex,
    key: &'static str,
    label_ja: &'static str,
    label_en: &'static str,
    group: TokenFieldGroupKey,
    order: u8,
    summary: bool,
    help: &'static str,
) -> TokenFieldMeta {
    TokenFieldMeta {
        attribute,
        key,
        label_ja,
        label_en,
        group,
        order,
        summary,
        help,
    }
}

